export function getWorkspace(slug: string): ModuleWorkspace | undefined {
  const key = resolveWorkspaceSlug(slug)
  const ws = moduleWorkspaces[key]
  if (!ws) return undefined
  if (key === slug) return ws
  const mod = findModule(slug)
  return {
    ...ws,
    slug,
    plural: mod?.label ?? ws.plural,
  }
}
