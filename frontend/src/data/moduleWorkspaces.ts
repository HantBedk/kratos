export type ModuleRecord = {
  id: string
  code: string
  title: string
  party: string
  amount?: number
  date: string
  status: string
  statusTone: BadgeTone
  notes: string
  fields: { label: string; value: string }[]
}

export type ModuleWorkspace = {
  slug: string
  singular: string
  plural: string
  createLabel: string
  searchPlaceholder: string
  filters: string[]
  stats: { label: string; value: string }[]
  records: ModuleRecord[]
  formHints: { title: string; party: string; amount?: boolean; notes: string }
  workflow: string[]
}

function r(
  partial: Omit<ModuleRecord, 'fields'> & { fields?: ModuleRecord['fields'] },
): ModuleRecord {
  return {
    ...partial,
    fields: partial.fields ?? [
      { label: 'Código', value: partial.code },
      { label: 'Responsable / tercero', value: partial.party },
      { label: 'Fecha', value: partial.date },
      ...(partial.amount != null ? [{ label: 'Valor (COP)', value: formatCOP(partial.amount) }] : []),
      { label: 'Estado', value: partial.status },
    ],
  }
}

